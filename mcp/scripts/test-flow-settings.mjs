// Existing Flow node inspector: readable settings, inline help, and sequence rows.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {FactSimRuntime} from '../dist/fact-sim-runtime.js';
const repoRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const runtime=new FactSimRuntime({repoRoot,preferredPort:0}),errors=[];
try{
  const page=await runtime.ensureReady();page.on('pageerror',e=>errors.push(e.message));
  const setup=await page.evaluate(()=>{
    const A=App,M=A.FlowViewModel,n=A.graph._nodes.find(n=>M.runtime(n)==='source');
    const registry=A.entityModelForGraph(A.graph);
    registry.upsert({typeId:'settings-a',name:'検証ワーク A'});registry.upsert({typeId:'settings-b',name:'検証ワーク B'});
    const rule=M.build(n).nodes.find(s=>s.kind==='rule' && s.ref.direction==='output');
    M.commit(A.graph,n.id,rule.ref,[{mode:'sequence',entries:[{typeId:'settings-a',quantity:1},{typeId:'settings-b',quantity:2}]}]);
    const before=JSON.stringify(A.graph.serialize());A.selectionInspector.setNode(n);
    const panel=document.getElementById('selectionInspectorPanel');document.body.append(panel);panel.style.cssText='display:block;position:fixed;inset:0;overflow:auto;z-index:99999;background:white';
    window.__settingsNode=n.id;
    return {before,key:rule.key};
  });
  assert.equal(await page.locator('.flowBasic').count(),0);
  await page.locator('.flowViewCanvas').waitFor({state:'visible'});
  await page.locator('.flowViewPicker').selectOption(setup.key);
  assert.equal(await page.locator('.flowSequenceRow').count(),2);
  assert.equal(await page.locator('.flowViewEditor textarea').count(),0);
  assert.equal(await page.evaluate(()=>JSON.stringify(App.graph.serialize())),setup.before);
  await page.getByLabel('1 番目の個数',{exact:true}).fill('3');
  await page.getByLabel('1 番目の個数',{exact:true}).press('Tab');
  const entries=()=>page.evaluate(()=>App.graph.getNodeById(window.__settingsNode).properties.outputRules[0].targets[0].entries);
  assert.equal((await entries())[0].quantity,3);
  await page.locator('.flowSequenceRow').first().getByRole('button',{name:'下へ',exact:true}).click();
  assert.equal((await entries())[0].typeId,'settings-b');
  await page.evaluate(()=>undo());
  await page.waitForFunction(()=>document.querySelector('[aria-label="1 番目のワーク"]')?.value==='settings-a');
  assert.equal((await entries())[0].quantity,3);
  await page.evaluate(()=>{const data=App.graph.serialize();App.injectEntityModel(data,App.graph);applySnapshot(JSON.stringify(data));App.selectionInspector.setNode(App.graph.getNodeById(window.__settingsNode));});
  await page.locator('.flowViewPicker').selectOption(setup.key);
  assert.equal(await page.getByLabel('1 番目の個数',{exact:true}).inputValue(),'3');
  await page.getByRole('button',{name:'生成するワークを追加',exact:true}).click();
  assert.equal((await entries()).length,3);
  await page.locator('.flowSequenceRow').last().getByRole('button',{name:'削除',exact:true}).click();
  assert.equal((await entries()).length,2);
  await fs.mkdir(path.join(repoRoot,'tmp'),{recursive:true});
  await page.locator('.flowViewEditor').scrollIntoViewIfNeeded();
  await page.locator('.flowViewEditor').screenshot({path:path.join(repoRoot,'tmp','flow-settings-sequence.png')});
  const condition=await page.evaluate(()=>{
    const n=App.graph._nodes.find(n=>App.FlowViewModel.runtime(n)==='machine');App.selectionInspector.setNode(n);
    const spec=App.FlowViewModel.build(n).nodes.find(s=>s.kind==='condition' && s.ref && s.ref.path.length===1);
    return {key:spec.key,before:JSON.stringify(App.graph.serialize())};
  });
  await page.getByRole('button',{name:'詳細表示',exact:true}).click();
  await page.locator('.flowViewPicker').selectOption(condition.key);
  assert.equal(await page.locator('.flowSettingMore').evaluate(e=>e.open),false);
  await page.locator('.flowSettingMore > summary').click();
  assert.equal(await page.evaluate(()=>JSON.stringify(App.graph.serialize())),condition.before);
  await page.getByRole('button',{name:'条件を反転する（NOT）',exact:true}).click();
  assert.equal(await page.getByLabel('条件',{exact:true}).inputValue(),'not');
  await page.evaluate(()=>undo());
  await page.waitForFunction(()=>document.querySelector('.flowViewEditor select[aria-label="条件"]')?.value!=='not');
  assert.equal(await page.evaluate(()=>JSON.stringify(App.graph.serialize())),condition.before);
  await page.locator('.flowViewEditor').scrollIntoViewIfNeeded();
  await page.locator('.flowViewEditor').screenshot({path:path.join(repoRoot,'tmp','flow-settings-condition.png')});
  await page.setViewportSize({width:390,height:844});
  await page.locator('.flowViewEditor').scrollIntoViewIfNeeded();
  const narrow=await page.evaluate(()=>{const p=document.getElementById('selectionInspectorPanel');return p.scrollWidth<=p.clientWidth+2;});assert(narrow);
  assert.deepEqual(errors,[]);
  const result={existingFlow:true,sequenceEditing:true,reorder:true,undo:true,json:true,conditionComposition:true,narrow,errors};
  await fs.mkdir(path.join(repoRoot,'artifacts','flow-settings'),{recursive:true});
  await fs.writeFile(path.join(repoRoot,'artifacts','flow-settings','validation.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
}finally{await runtime.close();}
